"""
Analyze Soccer Twos Evaluation Results

This script reads the evaluation_results.txt file generated by the Unity environment
and calculates win rates for each team.

Result codes:
- 0: Draw/Timeout
- 1: Blue team won
- 2: Purple team won

Usage: python analyze_evaluation.py [--file <path_to_results>]
"""

import argparse
import os


def analyze_results(file_path):
    """
    Analyze the evaluation results from the text file.
    
    Args:
        file_path: Path to the evaluation results file
    
    Returns:
        Dictionary containing win rate statistics
    """
    if not os.path.exists(file_path):
        print(f"Error: File not found: {file_path}")
        return None
    
    # Read results
    results = []
    with open(file_path, 'r') as f:
        for line in f:
            line = line.strip()
            if line and line.isdigit():
                results.append(int(line))
    
    if not results:
        print("No results found in the file.")
        return None
    
    # Count outcomes
    draws = results.count(0)
    blue_wins = results.count(1)
    purple_wins = results.count(2)
    total = len(results)
    
    # Calculate statistics
    stats = {
        'total_matches': total,
        'draws': draws,
        'blue_wins': blue_wins,
        'purple_wins': purple_wins,
        'draw_rate': draws / total * 100 if total > 0 else 0,
        'blue_win_rate': blue_wins / total * 100 if total > 0 else 0,
        'purple_win_rate': purple_wins / total * 100 if total > 0 else 0,
    }
    
    # Print results
    print("=" * 60)
    print("SOCCER TWOS EVALUATION RESULTS")
    print("=" * 60)
    print(f"Total Matches: {total}")
    print()
    print("Match Outcomes:")
    print(f"  Blue Wins:    {blue_wins:4d} ({stats['blue_win_rate']:5.1f}%)")
    print(f"  Purple Wins:  {purple_wins:4d} ({stats['purple_win_rate']:5.1f}%)")
    print(f"  Draws:        {draws:4d} ({stats['draw_rate']:5.1f}%)")
    print()
    
    # Determine overall winner
    if blue_wins > purple_wins:
        win_margin = blue_wins - purple_wins
        print(f"Overall Winner: Blue Team (+{win_margin} matches)")
    elif purple_wins > blue_wins:
        win_margin = purple_wins - blue_wins
        print(f"Overall Winner: Purple Team (+{win_margin} matches)")
    else:
        print("Overall Result: Tied")
    
    print("=" * 60)
    
    return stats


def main():
    parser = argparse.ArgumentParser(
        description="Analyze Soccer Twos evaluation results"
    )
    parser.add_argument(
        "--file",
        type=str,
        default="evaluation_results.txt",
        help="Path to the evaluation results file"
    )
    
    args = parser.parse_args()
    
    # Analyze results
    analyze_results(args.file)


if __name__ == "__main__":
    main()
